import catalogueFixture from "./fixtures/catalogue.json";

type Row = Record<string, unknown>;
type Day = { day_index: number; day_type: string; focus: string | null; label: string | null };

const USER = "u-m1";
const catalogue = (catalogueFixture as unknown as Row[]).map((e) => ({ ...e, is_active: true }));

let failures = 0;
function check(label: string, ok: boolean, detail = "") {
  if (!ok) failures++;
  console.log(`  ${ok ? "✓ PASS" : "❌ FAIL"} ${label}${detail ? `  -- ${detail}` : ""}`);
}

type Profile = { days_per_week: number; yoga_days_per_week: number; primary_track: string };

/** program_days rows exactly as the REAL generator lays out a block. */
function generatedDays(profile: Profile, blockNumber: number, startedOn?: string): Day[] {
  const input: GeneratorInput = {
    userId: USER,
    blockNumber,
    goal: "muscle_gain",
    level: "intermediate",
    primaryTrack: profile.primary_track as GeneratorInput["primaryTrack"],
    daysPerWeek: profile.days_per_week,
    yogaDaysPerWeek: profile.yoga_days_per_week,
    age: 30,
    bmi: 23,
    hasAllEquipment: true,
    equipmentIds: [],
    ...buildInjuryFlags([]),
    preferredSessionMinutes: 45,
    catalogue: catalogue as unknown as CandidateExercise[],
    startedOn,
  };
  return generateProgram(input).days.map((d) => ({
    day_index: d.dayIndex,
    day_type: d.dayType,
    focus: d.focus ?? null,
    label: d.label ?? null,
  }));
}

/** "3:Upper" for every scheduled (non-rest) day, in weekday order. */
function week(days: Array<{ day_index: number; day_type: string; label: string | null }>): string[] {
  return days
    .filter((d) => d.day_type !== "rest")
    .sort((a, b) => a.day_index - b.day_index)
    .map((d) => `${d.day_index}:${d.label}`);
}

type Fake = {
  client: SupabaseClient<Database>;
  rpcs: Array<{ name: string; payload: Row; today: string }>;
  programs: Row[];
  days: Array<Day & { program_id: string; status: string }>;
};

function makeFake(opts: {
  profile: Profile;
  programs: Row[];
  days: Record<string, Day[]>;
  failProgramDaysRead?: boolean;
}): Fake {
  const programs = opts.programs.map((p) => ({ ...p }));
  const days: Fake["days"] = [];
  for (const [programId, list] of Object.entries(opts.days)) {
    for (const d of list) days.push({ ...d, program_id: programId, status: "active" });
  }
  const profile: Row = {
    id: USER, timezone: "UTC", goal: "muscle_gain", level: "intermediate",
    primary_track: opts.profile.primary_track, days_per_week: opts.profile.days_per_week,
    yoga_days_per_week: opts.profile.yoga_days_per_week, has_all_equipment: true,
    height_cm: null, date_of_birth: null, preferred_session_minutes: 45, units: "kg",
  };
  const tables: Record<string, Row[]> = {
    profiles: [profile], programs, program_days: days as unknown as Row[], program_day_exercises: [],
    body_metrics: [], user_equipment: [], user_injuries: [], exercises: catalogue,
  };
  const rpcs: Fake["rpcs"] = [];

  function from(table: string) {
    const preds: Array<(r: Row) => boolean> = [];
    let order: { col: string; asc: boolean } | null = null;
    let limit: number | null = null;
    let inserted: Row[] | null = null;
    let updating: Row | null = null;
    const c: Record<string, unknown> = {};
    c.select = () => c;
    c.insert = (v: Row | Row[]) => {
      const list = (Array.isArray(v) ? v : [v]).map((r, i) => ({ id: `${table}-${tables[table].length + i}`, status: "active", ...r }));
      tables[table].push(...list);
      inserted = list;
      return c;
    };
    c.update = (v: Row) => { updating = v; return c; };
    c.eq = (col: string, v: unknown) => { preds.push((r) => r[col] === v); return c; };
    c.neq = (col: string, v: unknown) => { preds.push((r) => r[col] !== v); return c; };
    c.lt = (col: string, v: number) => { preds.push((r) => (r[col] as number) < v); return c; };
    c.in = (col: string, v: unknown[]) => { preds.push((r) => v.includes(r[col])); return c; };
    c.order = (col: string, o?: { ascending?: boolean }) => { order = { col, asc: o?.ascending !== false }; return c; };
    c.limit = (n: number) => { limit = n; return c; };
    const rows = (): Row[] => {
      if (inserted) return inserted;
      let out = (tables[table] ?? []).filter((r) => preds.every((p) => p(r)));
      if (updating) { for (const r of out) Object.assign(r, updating); return out; }
      if (order) {
        const { col, asc } = order;
        out = [...out].sort((a, b) => (a[col]! > b[col]! ? 1 : a[col]! < b[col]! ? -1 : 0) * (asc ? 1 : -1));
      }
      if (limit !== null) out = out.slice(0, limit);
      return out;
    };
    const run = (terminal: string) => {
      if (opts.failProgramDaysRead && table === "program_days" && !inserted) {
        return { data: null, error: { message: "program_days read failed (fake)" } };
      }
      const r = rows();
      if (terminal === "single") return r.length === 1 ? { data: r[0], error: null } : { data: null, error: { message: `single: ${r.length} rows` } };
      if (terminal === "maybeSingle") return r.length <= 1 ? { data: r[0] ?? null, error: null } : { data: null, error: { message: `maybeSingle: ${r.length} rows` } };
      return { data: r, error: null };
    };
    c.single = () => Promise.resolve(run("single"));
    c.maybeSingle = () => Promise.resolve(run("maybeSingle"));
    c.then = (res: (v: unknown) => unknown, rej: (e: unknown) => unknown) => Promise.resolve(run("await")).then(res, rej);
    return c;
  }

  function storeDays(programId: string, payload: Row) {
    for (const d of payload.days as Day[]) {
      days.push({ day_index: d.day_index, day_type: d.day_type, focus: d.focus, label: d.label, program_id: programId, status: "active" });
    }
  }

  async function rpc(name: string, args: Row) {
    const payload = args.p_payload as Row;
    const today = args.p_today as string;
    rpcs.push({ name, payload, today });
    if (name === "rollover_block") {
      // Mirrors rollover_block: close the ended block as completed, open the next.
      let startedOn = today;
      for (const p of programs) {
        if (p.status !== "active") continue;
        const ends = p.ends_on as string;
        if (today <= ends) return { data: null, error: { message: "rollover_block: block has not ended" } };
        startedOn = today > addDays(ends, 1) ? today : addDays(ends, 1);
        p.status = "completed";
        p.ended_on = ends;
      }
      programs.push({ id: payload.id, user_id: USER, block_number: payload.block_number, started_on: startedOn, ends_on: addDays(startedOn, 27), ended_on: null, status: "active" });
      storeDays(payload.id as string, payload);
      return { data: payload.id, error: null };
    }
    if (name === "rebuild_block") {
      // Mirrors rebuild_block mid-block: the active row is superseded by the new one.
      const active = programs.find((p) => p.status === "active");
      if (active) active.status = "superseded";
      programs.push({ id: payload.id, user_id: USER, block_number: payload.block_number, started_on: active?.started_on ?? today, ends_on: active?.ends_on, ended_on: null, status: "active" });
      storeDays(payload.id as string, payload);
      return { data: payload.id, error: null };
    }
    return { data: null, error: { message: `unexpected rpc ${name}` } };
  }

  return { client: { from, rpc } as unknown as SupabaseClient<Database>, rpcs, programs, days };
}

function payloadWeek(payload: Row | undefined): string[] {
  return week(((payload?.days as Day[] | undefined) ?? []));
}

const FOUR: Profile = { days_per_week: 4, yoga_days_per_week: 0, primary_track: "weights" };
const THREE: Profile = { days_per_week: 3, yoga_days_per_week: 0, primary_track: "weights" };
const WED_B1 = "2026-09-30"; // a Wednesday; block 1 ends 2026-10-27
const block1 = (endsOn = "2026-10-27", startedOn = WED_B1): Row => ({
  id: "b1", user_id: USER, block_number: 1, started_on: startedOn, ends_on: endsOn, ended_on: null, status: "active",
});

async function main() {
  console.log("\nQA2 M-1: block 2+ keeps the member's weekdays (real rollover / rebuild / createBlockForUser)\n");

  const wedFour = generatedDays(FOUR, 1, WED_B1);
  const WED_WEEK = ["3:Upper", "4:Lower", "6:Upper", "7:Lower"];
  check("fixture: #165 anchors a Wednesday 4-day block 1 to Wed Upper / Thu Lower / Sat Upper / Sun Lower",
    JSON.stringify(week(wedFour)) === JSON.stringify(WED_WEEK), JSON.stringify(week(wedFour)));

  console.log("\n1. Rollover (block 1 ended yesterday, Today opened 2026-10-28)");
  {
    const f = makeFake({ profile: FOUR, programs: [block1()], days: { b1: wedFour } });
    const res = await ensureCurrentBlock(f.client, USER, "2026-10-28");
    check("rolled over to block 2", res.status === "rolled_over" && res.blockNumber === 2, JSON.stringify(res));
    const roll = f.rpcs.find((r) => r.name === "rollover_block");
    check("block 2 keeps Wed Upper / Thu Lower / Sat Upper / Sun Lower (not Mon/Tue/Thu/Fri)",
      JSON.stringify(payloadWeek(roll?.payload)) === JSON.stringify(WED_WEEK), JSON.stringify(payloadWeek(roll?.payload)));
    check("Wednesday (today) is a training day in block 2",
      ((roll?.payload.days as Day[] | undefined) ?? []).some((d) => d.day_index === 3 && d.day_type === "weights"));
  }

  console.log("\n2. Missed-days rollover (block 1 ended 2026-10-22, away 5 days, back 2026-10-28)");
  {
    const f = makeFake({ profile: FOUR, programs: [block1("2026-10-22", "2026-09-24")], days: { b1: generatedDays(FOUR, 1, "2026-09-24") } });
    const prevWeek = week(generatedDays(FOUR, 1, "2026-09-24"));
    const res = await ensureCurrentBlock(f.client, USER, "2026-10-28");
    check("rolled over to block 2", res.status === "rolled_over", JSON.stringify(res));
    const roll = f.rpcs.find((r) => r.name === "rollover_block");
    check("block 2 keeps block 1's Thursday-anchored week after the gap",
      JSON.stringify(payloadWeek(roll?.payload)) === JSON.stringify(prevWeek) && prevWeek[0] !== "1:Upper",
      `${JSON.stringify(payloadWeek(roll?.payload))} vs ${JSON.stringify(prevWeek)}`);
  }

  console.log("\n3. Settings rebuild after block 1 ended (rebuildPlanCore: rollover, then rebuild of block 2)");
  {
    const f = makeFake({ profile: FOUR, programs: [block1()], days: { b1: wedFour } });
    const res = await rebuildPlanCore(buildRebuildPlanDeps(f.client, USER, "2026-10-28"));
    check("rebuild succeeds", res.ok === true, JSON.stringify(res));
    const names = f.rpcs.map((r) => r.name);
    check("RPCs are [rollover_block, rebuild_block]", JSON.stringify(names) === JSON.stringify(["rollover_block", "rebuild_block"]), JSON.stringify(names));
    const reb = f.rpcs.find((r) => r.name === "rebuild_block");
    check("rebuild targets block 2", reb?.payload.block_number === 2, String(reb?.payload.block_number));
    check("rolled-over block 2 keeps the Wednesday week",
      JSON.stringify(payloadWeek(f.rpcs[0]?.payload)) === JSON.stringify(WED_WEEK), JSON.stringify(payloadWeek(f.rpcs[0]?.payload)));
    check("rebuilt block 2 keeps the Wednesday week",
      JSON.stringify(payloadWeek(reb?.payload)) === JSON.stringify(WED_WEEK), JSON.stringify(payloadWeek(reb?.payload)));
  }

  console.log("\n4. Mid-block rebuild of block 2 (createBlockForUser rebuild) keeps block 2's own week");
  {
    const b2 = generatedDays(FOUR, 1, WED_B1); // the week block 2 carried
    const f = makeFake({ profile: FOUR, programs: [
      { ...block1(), status: "completed", ended_on: "2026-10-27" },
      { id: "b2", user_id: USER, block_number: 2, started_on: "2026-10-28", ends_on: "2026-11-24", ended_on: null, status: "active" },
    ], days: { b1: [], b2 } });
    const res = await createBlockForUser(f.client, USER, { mode: "rebuild", today: "2026-11-02" });
    check("rebuild ok, block 2", res.ok && res.blockNumber === 2, JSON.stringify(res));
    check("rebuilt block 2 keeps Wed/Thu/Sat/Sun",
      JSON.stringify(payloadWeek(f.rpcs[0]?.payload)) === JSON.stringify(WED_WEEK), JSON.stringify(payloadWeek(f.rpcs[0]?.payload)));
  }

  console.log("\n5. New block 2 via createBlockForUser (\"new\") keeps the previous block's week");
  {
    const f = makeFake({ profile: FOUR, programs: [block1()], days: { b1: wedFour } });
    const res = await createBlockForUser(f.client, USER, { today: "2026-10-28" });
    check("built block 2", res.ok && res.blockNumber === 2, JSON.stringify(res));
    const programId = res.ok ? res.programId : "";
    check("inserted block 2 days keep Wed/Thu/Sat/Sun",
      JSON.stringify(week(f.days.filter((d) => d.program_id === programId))) === JSON.stringify(WED_WEEK),
      JSON.stringify(week(f.days.filter((d) => d.program_id === programId))));
  }

  console.log("\n6. Block 3 from a carried block 2 (3 days, Thursday sign-up: Thu A / Sat B / Mon C)");
  {
    const thuThree = generatedDays(THREE, 1, "2026-10-01"); // Thursday
    const THU_WEEK = ["1:Full Body C", "4:Full Body A", "6:Full Body B"];
    check("fixture: Thursday 3-day block 1 is Thu A / Sat B / Mon C", JSON.stringify(week(thuThree)) === JSON.stringify(THU_WEEK), JSON.stringify(week(thuThree)));
    const f = makeFake({ profile: THREE, programs: [block1("2026-10-28", "2026-10-01")], days: { b1: thuThree } });
    await ensureCurrentBlock(f.client, USER, "2026-10-29");
    check("block 2 keeps each weekday's session (Thu A, Sat B, Mon C)",
      JSON.stringify(payloadWeek(f.rpcs[0]?.payload)) === JSON.stringify(THU_WEEK), JSON.stringify(payloadWeek(f.rpcs[0]?.payload)));
    f.programs[f.programs.length - 1].ends_on = "2026-11-25";
    await ensureCurrentBlock(f.client, USER, "2026-11-26");
    check("block 3 still keeps Thu A, Sat B, Mon C",
      f.rpcs[1]?.payload.block_number === 3 && JSON.stringify(payloadWeek(f.rpcs[1]?.payload)) === JSON.stringify(THU_WEEK),
      JSON.stringify(payloadWeek(f.rpcs[1]?.payload)));
  }

  console.log("\n7. Pre-#165 member (block 1 on the default Mon/Wed/Fri) keeps Mon/Wed/Fri");
  {
    const f = makeFake({ profile: THREE, programs: [block1("2026-10-28", "2026-10-01")], days: { b1: generatedDays(THREE, 1) } });
    await ensureCurrentBlock(f.client, USER, "2026-10-29");
    check("block 2 is Mon A / Wed B / Fri C",
      JSON.stringify(payloadWeek(f.rpcs[0]?.payload)) === JSON.stringify(["1:Full Body A", "3:Full Body B", "5:Full Body C"]),
      JSON.stringify(payloadWeek(f.rpcs[0]?.payload)));
  }

  console.log("\n8. Explicit day change in Settings wins (4-day Wednesday week, days_per_week now 3)");
  {
    const f = makeFake({ profile: THREE, programs: [block1()], days: { b1: wedFour } });
    const res = await rebuildPlanCore(buildRebuildPlanDeps(f.client, USER, "2026-10-28"));
    check("rebuild succeeds", res.ok === true, JSON.stringify(res));
    const reb = f.rpcs.find((r) => r.name === "rebuild_block");
    check("block 2 uses the 3-day default Mon/Wed/Fri, not the old weekdays",
      JSON.stringify(payloadWeek(reb?.payload)) === JSON.stringify(["1:Full Body A", "3:Full Body B", "5:Full Body C"]),
      JSON.stringify(payloadWeek(reb?.payload)));
  }

  console.log("\n9. Yoga keeps all its days (5 days with 2 yoga, Wednesday sign-up)");
  {
    const yogaMix: Profile = { days_per_week: 5, yoga_days_per_week: 2, primary_track: "weights" };
    const b1 = generatedDays(yogaMix, 1, WED_B1);
    const f = makeFake({ profile: yogaMix, programs: [block1()], days: { b1 } });
    await ensureCurrentBlock(f.client, USER, "2026-10-28");
    const got = payloadWeek(f.rpcs[0]?.payload);
    check("block 2 keeps all 5 days, yoga on the same weekdays",
      got.length === 5 && JSON.stringify(got) === JSON.stringify(week(b1)), `${JSON.stringify(got)} vs ${JSON.stringify(week(b1))}`);

    const yogaTrack: Profile = { days_per_week: 5, yoga_days_per_week: 0, primary_track: "yoga" };
    const y1 = generatedDays(yogaTrack, 1, WED_B1);
    const g = makeFake({ profile: yogaTrack, programs: [block1()], days: { b1: y1 } });
    await ensureCurrentBlock(g.client, USER, "2026-10-28");
    const yg = payloadWeek(g.rpcs[0]?.payload);
    check("yoga-led plan keeps its 5 yoga days", yg.length === 5 && yg.every((d) => d.endsWith(":Yoga")) && JSON.stringify(yg) === JSON.stringify(week(y1)), JSON.stringify(yg));
  }

  console.log("\n10. A failed read of the ended block's days fails the rollover instead of moving days");
  {
    const f = makeFake({ profile: FOUR, programs: [block1()], days: { b1: wedFour }, failProgramDaysRead: true });
    const origError = console.error;
    console.error = () => {};
    const res = await ensureCurrentBlock(f.client, USER, "2026-10-28").finally(() => { console.error = origError; });
    check("rollover returns an error", res.status === "error", JSON.stringify(res));
    check("no rollover_block RPC was sent", f.rpcs.length === 0, JSON.stringify(f.rpcs.map((r) => r.name)));
  }

  console.log("\n11. carriedWeekdayLayout edge cases");
  {
    check("no previous block -> null (default mapping)", carriedWeekdayLayout([], 4, 0) === null);
    check("days_per_week changed -> null", carriedWeekdayLayout(wedFour, 3, 0) === null);
    check("Wednesday 4-day -> [3,4,6,7]", JSON.stringify(carriedWeekdayLayout(wedFour, 4, 0)) === "[3,4,6,7]", JSON.stringify(carriedWeekdayLayout(wedFour, 4, 0)));
    const unlabeled = wedFour.map((d) => ({ ...d, label: null, focus: null }));
    check("labels that match nothing keep the weekdays, earliest first", JSON.stringify(carriedWeekdayLayout(unlabeled, 4, 0)) === "[3,4,6,7]", JSON.stringify(carriedWeekdayLayout(unlabeled, 4, 0)));
  }

  console.log(failures === 0 ? "\n✓ block weekday carry-over tests passed\n" : `\n❌ ${failures} check(s) failed\n`);
  if (failures > 0) process.exit(1);
}

main().catch((e) => {
  console.error(e);
  process.exit(1);
});

export {};
