#!/usr/bin/env tsx
/**
 * QA2 M-1: a new block (2+) keeps the member's weekdays.
 *
 * Bug: generate.ts anchored only block 1 (#165), so when block 1 ended every
 * later block fell back to the default `activeDayIndices` week. A Wednesday
 * sign-up on 4 days (Wed Upper / Thu Lower / Sat Upper / Sun Lower) was moved
 * to Mon/Tue/Thu/Fri on rollover, on a missed-days rollover and on a Settings
 * rebuild after the block ended, and Wednesday became a rest day.
 *
 * Decision (coordinator): every new block keeps the PREVIOUS block's actual
 * training weekdays; pre-#165 members keep Mon/Wed/Fri; an explicit day change
 * in Settings (days_per_week) still wins; yoga keeps all of its days.
 *
 * Drives the REAL code paths with a stateful fake Supabase client:
 *   - ensureCurrentBlock (src/lib/program/rollover.ts) -> rollover_block payload
 *   - rebuildPlanCore + buildRebuildPlanDeps (the Settings rebuild) -> rollover_block
 *     then rebuild_block payloads
 *   - createBlockForUser (src/lib/program/persist.ts), "new" and "rebuild"
 * Block 1 fixtures are generated by the REAL generateProgram anchored to the
 * sign-up date, so they are exactly what #165 writes.
 *
 * Killed mutants: scripts/test-block-weekday-carryover-mutants.sh (mktemp copies).
 *
 *   npx tsx scripts/test-block-weekday-carryover.ts
 */

